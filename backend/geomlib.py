"""Geometry tab backend: detector catalog, material list, geometry documents,
and headless Geant4 validation.

Data model
----------
- Catalog:   $NPTOOL/NPSimulation/ressources/detectors.json — generated by the
  nptool build (extract-detector-schema.py). Per detector: block token, variant
  token lists, every field with type/unit/optional/description. The Geometry
  tab renders its forms from this file, nothing is hardcoded in the frontend.
- Materials: $NPTOOL/NPSimulation/ressources/materials.txt (shipped library)
  overlaid by the user workspace inputs/materials.txt. Parsed into a table for
  material pickers.
- Documents: user/<key>/geometries/<name>.geo — NPL block text holding `Solid`
  and `Volume` blocks (the script-defined geometry). The GUI round-trips this
  text; "apply" splices a document into the detector slot between markers so
  several documents can coexist with regular detector blocks.
- Validate:  run npsimulation headless on a document (construct + overlap
  check + /det/export_geometry), return warnings and the exact viewer scene.
"""
from __future__ import annotations

import json
import re
import shutil
import subprocess
import uuid
from pathlib import Path

import common
import config
import inputs
import scene

# ── nptool-side resources ──────────────────────────────────────────────────────
_CATALOG_PATH = Path(config.NPTOOL_ROOT) / "NPSimulation" / "ressources" / "detectors.json"
_MATERIALS_SEED = Path(config.NPTOOL_ROOT) / "NPSimulation" / "ressources" / "materials.txt"

_catalog_cache: tuple[float, dict] | None = None

VALIDATE_TIMEOUT_SEC = 180

# markers used when splicing a geometry document into detector.txt
_MARK_BEGIN = "%== nptoy geometry \"{name}\" begin (managed block, do not edit) ==%"
_MARK_END = "%== nptoy geometry \"{name}\" end ==%"


def catalog() -> dict:
    """detectors.json, cached by mtime. Raises FileNotFoundError if the nptool
    tree has no generated catalog (build not run)."""
    global _catalog_cache
    mtime = _CATALOG_PATH.stat().st_mtime
    if _catalog_cache and _catalog_cache[0] == mtime:
        return _catalog_cache[1]
    data = json.loads(_CATALOG_PATH.read_text())
    _catalog_cache = (mtime, data)
    return data


# ── materials table ────────────────────────────────────────────────────────────
def _parse_material_file(path: Path, origin: str) -> list[dict]:
    """Minimal NPL-block reader for materials.txt: enough for a picker table
    (name, aliases, density string, state, composition summary)."""
    if not path.exists():
        return []
    entries: list[dict] = []
    cur: dict | None = None
    for raw in path.read_text(errors="replace").splitlines():
        line = raw.split("%", 1)[0].rstrip()
        if not line.strip():
            continue
        if not raw[0].isspace():  # block head: "Material <name>"
            parts = line.split()
            cur = None
            if len(parts) >= 2 and parts[0] == "Material":
                cur = {"name": parts[1], "aliases": [], "origin": origin}
                entries.append(cur)
            continue
        if cur is None or "=" not in line:
            continue
        token, value = (s.strip() for s in line.split("=", 1))
        if token == "Aliases":
            cur["aliases"] = value.split()
        elif token in ("Density", "State"):
            cur[token.lower()] = value
        elif token == "Elements":
            cur["elements"] = value.split()
    return entries


def materials(user_key: str | None = None) -> list[dict]:
    """Shipped material library + the user's workspace overlay (later wins)."""
    table: dict[str, dict] = {}
    for e in _parse_material_file(_MATERIALS_SEED, "library"):
        table[e["name"]] = e
    if user_key:
        ws = inputs.root(user_key) / "materials.txt"
        for e in _parse_material_file(ws, "workspace"):
            table[e["name"]] = e
    return sorted(table.values(), key=lambda e: e["name"].lower())


# ── geometry documents ─────────────────────────────────────────────────────────
def _docs_dir(user_key: str) -> Path:
    d = config.USERS_ROOT / user_key / "geometries"
    d.mkdir(parents=True, exist_ok=True)
    return d


def _safe_name(name: str) -> str:
    name = (name or "").strip()
    if not re.fullmatch(r"[A-Za-z0-9_\- ]{1,64}", name):
        raise ValueError("geometry name must be 1-64 chars of letters, digits, _ - or space")
    return name


def list_docs(user_key: str) -> list[dict]:
    out = []
    for p in sorted(_docs_dir(user_key).glob("*.geo")):
        text = p.read_text(errors="replace")
        out.append({
            "name": p.stem,
            "volumes": len(re.findall(r"^Volume\s+\S+", text, re.M)),
            "solids": len(re.findall(r"^Solid\s+\S+", text, re.M)),
            "applied": _find_region(_detector_text(user_key), p.stem) is not None,
        })
    return out


def read_doc(user_key: str, name: str) -> str:
    p = _docs_dir(user_key) / (_safe_name(name) + ".geo")
    if not p.exists():
        raise FileNotFoundError(name)
    return p.read_text(errors="replace")


def write_doc(user_key: str, name: str, content: str) -> None:
    (_docs_dir(user_key) / (_safe_name(name) + ".geo")).write_text(content)


def delete_doc(user_key: str, name: str) -> None:
    remove_from_detector(user_key, name)          # drop the applied region too
    p = _docs_dir(user_key) / (_safe_name(name) + ".geo")
    if p.exists():
        p.unlink()


def rename_doc(user_key: str, name: str, new: str) -> None:
    src = _docs_dir(user_key) / (_safe_name(name) + ".geo")
    dst = _docs_dir(user_key) / (_safe_name(new) + ".geo")
    if not src.exists():
        raise FileNotFoundError(name)
    if dst.exists():
        raise ValueError(f'geometry "{new}" already exists')
    applied = _find_region(_detector_text(user_key), name) is not None
    if applied:
        remove_from_detector(user_key, name)
    src.rename(dst)
    if applied:
        apply_to_detector(user_key, new)


# ── splice documents into detector.txt ─────────────────────────────────────────
def _detector_text(user_key: str) -> str:
    try:
        return inputs.read_slot(user_key, "detector")
    except (ValueError, FileNotFoundError):
        return ""


def _find_region(text: str, name: str) -> tuple[int, int] | None:
    """(start, end) line indices of the managed region for `name`, inclusive."""
    begin, end = _MARK_BEGIN.format(name=name), _MARK_END.format(name=name)
    lines = text.splitlines()
    try:
        i = lines.index(begin)
        j = lines.index(end, i)
        return i, j
    except ValueError:
        return None


def apply_to_detector(user_key: str, name: str) -> None:
    """Insert (or refresh) the document's blocks in the detector slot, wrapped
    in named markers so they can be updated/removed without touching the rest
    of the file."""
    doc = read_doc(user_key, name)
    text = _detector_text(user_key)
    lines = text.splitlines()
    region = _find_region(text, name)
    if region:
        del lines[region[0] : region[1] + 1]
        insert_at = region[0]
    else:
        insert_at = len(lines)
        if lines and lines[-1].strip():
            lines.append("")
    block = [_MARK_BEGIN.format(name=name)] + doc.splitlines() + [_MARK_END.format(name=name)]
    lines[insert_at:insert_at] = block
    inputs.write_slot(user_key, "detector", "\n".join(lines) + "\n")


def remove_from_detector(user_key: str, name: str) -> bool:
    text = _detector_text(user_key)
    region = _find_region(text, name)
    if not region:
        return False
    lines = text.splitlines()
    del lines[region[0] : region[1] + 1]
    inputs.write_slot(user_key, "detector", "\n".join(lines) + "\n")
    return True


# ── headless validation ────────────────────────────────────────────────────────
_VALIDATE_REACTION = """Isotropic
 EnergyLow= 1 MeV
 EnergyHigh= 1 MeV
 HalfOpenAngleMin= 0 deg
 HalfOpenAngleMax= 180 deg
 x0= 0 mm
 y0= 0 mm
 z0= 0 mm
 Particle= gamma
 ExcitationEnergy= 0 MeV
"""


def validate(user_key: str, content: str) -> dict:
    """Build the geometry for real: run npsimulation headless on `content`
    (detector-file text), let Geant4 construct every volume, run the per-
    placement overlap check, export the exact scene, and report back.

    Local runner only (the Mac/dev path); returns ok/errors/warnings/log and
    the viewer scene list under "geometry".
    """
    if config.RUNNER != "local":
        raise RuntimeError("geometry validation runs on the local toolchain only (for now)")

    work = config.USERS_ROOT / user_key / ".geomcheck"
    if work.exists():
        shutil.rmtree(work)
    work.mkdir(parents=True)
    (work / "check.detector").write_text(content)
    (work / "check.reaction").write_text(_VALIDATE_REACTION)
    # user materials must resolve during validation too
    ws_mat = inputs.root(user_key) / "materials.txt"
    if ws_mat.exists():
        shutil.copy(ws_mat, work / "materials.txt")
    geom_path = work / "check.geom.json"
    (work / "check.mac").write_text(f"/det/export_geometry {geom_path}\n")

    out_name = f"__geomcheck_{uuid.uuid4().hex[:8]}"
    cmd = (
        f'source "{config.NPTOOL_SETUP}" >/dev/null 2>&1 && '
        f"exec npsimulation -D check.detector -E check.reaction -O {out_name}.root -B check.mac"
    )
    try:
        proc = subprocess.run(["bash", "-c", cmd], cwd=work, capture_output=True,
                              text=True, timeout=VALIDATE_TIMEOUT_SEC)
        timed_out = False
    except subprocess.TimeoutExpired as e:
        proc, timed_out = e, True

    stdout = (proc.stdout or "") + ("\n" + proc.stderr if proc.stderr else "")
    # stray ROOT output written under the nptool tree (no project.config here)
    stray = Path(config.NPTOOL_ROOT) / "Outputs" / "Simulation" / f"{out_name}.root"
    if stray.exists():
        stray.unlink()

    ansi = re.compile(r"\x1b\[[0-9;]*m")
    lines = [ansi.sub("", ln) for ln in stdout.splitlines()]
    errors = [ln for ln in lines if ln.startswith("ERROR")]
    overlaps = [ln for ln in lines if "overlap" in ln.lower() and "checking" not in ln.lower()]
    if timed_out:
        errors.append(f"validation timed out after {VALIDATE_TIMEOUT_SEC}s")

    geometry = []
    if geom_path.exists():
        try:
            geometry = scene.geometry(geom_path)
        except Exception as e:  # malformed export — report, don't 500
            errors.append(f"geometry export unreadable: {e}")

    exported = geom_path.exists()
    return {
        "ok": (not timed_out) and (not errors) and exported,
        "exported": exported,
        "errors": errors,
        "overlaps": overlaps,
        "geometry": geometry,
        "log": "\n".join(lines[-120:]),
    }
